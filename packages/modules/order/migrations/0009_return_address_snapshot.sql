-- M17 0009：同意退货时把退货地址**快照**到单据上（ADR-061）。
--
-- ADR-053 把退货地址放进店铺资料一处配置，ADR-051 让顾客在「待寄回」时看到它。
-- 但那是**实时读取**的：商家今天改地址，昨天已同意退货的顾客刷新页面就变成新地址 ——
-- 他手上的包裹可能已经按旧地址寄出了，两边永远对不上。
--
-- 退货地址在「同意退货」那一刻就是承诺。承诺要留痕，所以存一份在单据上：
--   - 顾客看到的是他当时被告知的那个地址（含商家后来改址也不会变）；
--   - 商家在售后单里能查「这单当时让寄到哪」，不必靠记忆。
--
-- 为什么允许为空：地址未配置时商家仍可同意退货（否则退款永远卡在待处理），
-- 此时快照为 null，顾客端提示「联系客服获取地址」——与 ADR-053 的降级一致。

ALTER TABLE refund_request ADD COLUMN IF NOT EXISTS return_address text;

COMMENT ON COLUMN refund_request.return_address IS '同意退货时快照的退货地址（null = 当时未配置）';
