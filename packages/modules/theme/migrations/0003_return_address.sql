-- M17 0003：退货地址（ADR-053）。
--
-- ADR-051 做完退货退款后留了一个断链：顾客被同意退货，却不知道货该寄到哪 ——
-- 只能去问客服。真实店铺的退货地址是固定配置（仓库或代收点），应当像店名一样一处配三处用。
--
-- 为什么是一个多行文本而不是结构化四段：
--   国内退货地址常带「转运仓编码」「某某代收点」这类非标准信息，
--   拆成省/市/区/详细地址反而装不下；一个文本框 + 换行，寄件时照抄就不会错。
--
-- 为什么不复用 stock_location 的仓库地址：
--   退货地址经常与发货仓不同（退到代收点、退到客服处），
--   混用会导致「发货单印 A 地址、顾客退回 B 地址」这种对不上的情况。

ALTER TABLE theme_settings ADD COLUMN IF NOT EXISTS return_address text;

COMMENT ON COLUMN theme_settings.return_address IS '退货收件地址（多行：收件人/电话/地址），顾客在退货流程里看到';
